"""The type stub for `fsw.codegen.fpp_types`, `fpp_types.pyi`, generated from the module and the contract.

The module binds each top-level FPP module's tuples at import, which a type checker cannot see.
The stub declares them: a class per FPP module, nested as the module is, holding a `NamedTuple`
per struct and per algorithm component's outputs, telemetry and parameters. A field is `np.ndarray`
for an array, `float`, `int` or `bool` for a number, the struct's own class for a struct, and `str`
for an enum or a string; an outputs or telemetry field is also `None`, which is a value not
written. The stub shadows the whole module for importers, so its static part, the functions and
annotated names `fpp_types.py` writes, is that file's own, read with `ast` and its bodies dropped.

`python -m fsw.codegen.fpp_types_stub` writes the stub beside `fpp_types.py`; CMake runs it during
`just fsw`.
"""

import ast
from pathlib import Path
from types import SimpleNamespace

import numpy as np

from fsw.codegen import fpp_types
from fsw.codegen.fields import form
from fsw.codegen.fpp_model import Component, Member, Struct, Types

__all__ = ["main", "render"]

_HEADER = "# Generated by fsw.codegen.fpp_types_stub; never committed."


def _static(source: str) -> list[str]:
    """The statements of a module that its stub keeps, as source.

    A docstring, an import, a function with its body cut to its docstring, and an annotated name
    without its value are kept; other statements are not.

    Args:
        source: the module's text.

    Returns:
        Each kept statement, in order.
    """
    module = ast.parse(source)
    kept: list[ast.stmt] = []
    for position, node in enumerate(module.body):
        if (position == 0 and isinstance(node, ast.Expr) and isinstance(node.value, ast.Constant)) or isinstance(
            node, ast.Import | ast.ImportFrom
        ):
            kept.append(node)
        elif isinstance(node, ast.FunctionDef):
            docstring = ast.get_docstring(node, clean=False)
            body: list[ast.stmt] = [ast.Expr(ast.Constant(docstring if docstring is not None else ...))]
            kept.append(
                ast.FunctionDef(
                    name=node.name,
                    args=node.args,
                    body=body,
                    decorator_list=node.decorator_list,
                    returns=node.returns,
                    type_params=node.type_params,
                )
            )
        elif isinstance(node, ast.AnnAssign):
            kept.append(ast.AnnAssign(node.target, node.annotation, None, node.simple))
    return [ast.unparse(ast.fix_missing_locations(node)) for node in kept]


def _annotation(member: Member, types: Types) -> str:
    """The annotation of a tuple field.

    Args:
        member: the field's FPP member.
        types: the model's types.

    Returns:
        `np.ndarray` for an array, `float`, `int` or `bool` for a number, a struct's qualified
        name, else `str`.

    Raises:
        ValueError: the field is a number of a kind the stub does not map, naming it.
    """
    shape, element = form(member, types)
    if shape:
        return "np.ndarray"
    if isinstance(element, np.dtype):
        names = {"f": "float", "i": "int", "u": "int", "b": "bool"}
        if element.kind not in names:
            raise ValueError(f"{member.name} is {element}, which the stub does not map")
        return names[element.kind]
    if isinstance(types.get(element), Struct):
        return element
    return "str"


def _fields(cls: type) -> list[tuple[Member, Types, str]]:
    """Each field of a generated tuple, with the model's types and how the tuple wraps it.

    Args:
        cls: a struct's tuple, or a component's outputs, telemetry or parameters tuple.

    Returns:
        `(member, types, kind)` per field in order, `kind` being `struct`, `Outputs`, `Telemetry`
        or `Parameters`.

    Raises:
        ValueError: the tuple is of neither a generated struct nor a generated component.
    """
    if cls in fpp_types._STRUCTS:
        struct, types = fpp_types._STRUCTS[cls]
        return [(member, types, "struct") for member in struct.members]
    for name, (component, types) in fpp_types._COMPONENTS.items():
        for suffix in ("Outputs", "Telemetry", "Parameters"):
            if fpp_types.named(name + suffix) is cls:
                return [(member, types, suffix) for member in _members(component, suffix)]
    raise ValueError(f"{cls.__qualname__} is not a generated tuple")


def _members(component: Component, kind: str) -> list[Member]:
    """The members behind a component's tuple.

    Args:
        component: the component.
        kind: `Outputs`, `Telemetry` or `Parameters`.

    Returns:
        A member per output port, channel or parameter, in the tuple's field order.
    """
    if kind == "Outputs":
        return [Member(p.name, p.args[0].type, None) for p in component.outputs]
    if kind == "Telemetry":
        return [Member(c.name, c.type, None) for c in component.channels]
    required = [p for p in component.parameters if p.default is None]
    defaulted = [p for p in component.parameters if p.default is not None]
    return [Member(p.name, p.type, None) for p in [*required, *defaulted]]


def _tuple(name: str, cls: type, depth: int) -> list[str]:
    """A tuple class as stub lines.

    Args:
        name: the class's name in its namespace.
        cls: the generated tuple.
        depth: how many levels of namespace it is nested in.

    Returns:
        The lines of its `NamedTuple` class.
    """
    pad = "    " * depth
    lines = [f"{pad}class {name}(NamedTuple):"]
    if hasattr(cls, "component"):
        lines.append(f"{pad}    component: ClassVar[str]")
    for member, types, kind in _fields(cls):
        annotation = _annotation(member, types)
        if kind in ("Outputs", "Telemetry"):
            lines.append(f"{pad}    {member.name}: {annotation} | None = ...")
        else:
            default = " = ..." if member.name in cls._field_defaults else ""
            lines.append(f"{pad}    {member.name}: {annotation}{default}")
    if len(lines) == 1:
        lines.append(f"{pad}    ...")
    return lines


def _namespace(name: str, space: SimpleNamespace, depth: int) -> list[str]:
    """A namespace and everything in it as stub lines.

    Args:
        name: the namespace's name.
        space: the namespace.
        depth: how many levels of namespace it is nested in.

    Returns:
        The lines of its class.
    """
    pad = "    " * depth
    lines = [f"{pad}class {name}:"]
    for member, value in vars(space).items():
        if isinstance(value, SimpleNamespace):
            lines += _namespace(member, value, depth + 1)
        else:
            lines += _tuple(member, value, depth + 1)
    if len(lines) == 1:
        lines.append(f"{pad}    ...")
    return lines


def render() -> str:
    """The stub of `fsw.codegen.fpp_types`.

    Returns:
        Its text.
    """
    parts = [_HEADER, *_static(Path(fpp_types.__file__).read_text())]
    parts += ["import numpy as np", "from typing import ClassVar, NamedTuple", f"__all__ = {fpp_types.__all__!r}"]
    lines = ["\n".join(parts)]
    for name in fpp_types.__all__:
        value = getattr(fpp_types, name)
        if isinstance(value, SimpleNamespace):
            lines.append("\n".join(_namespace(name, value, 0)))
    return "\n\n".join(lines) + "\n"


def main() -> None:
    """Writes the stub beside `fpp_types.py`."""
    Path(fpp_types.__file__).with_suffix(".pyi").write_text(render())


if __name__ == "__main__":
    main()
