"""The F´ build's CDH component, `Cdh.BusConverter`, generated from its FPP declaration.

For each role `fsw.codegen.roles` reads, `render` emits a conversion `convert_<role>`, inline in
the header, building the struct the role's `<role>Out` sends from the one its `<role>In` takes by
`fsw.codegen.fields.plan`: a sensor's GNC struct from its bus struct, an actuator's bus struct from
its GNC struct. It also emits a handler sending the conversion's result on `<role>Out`. A field
outside `fsw.codegen.fields.STRUCT_PRIMITIVES` raises when the code is generated.

It also emits the lab's test pins, `BusConverterPins.hpp`, which each configuration's extension,
`_wise_fsw_<configuration>`, includes once: `bus_<Struct>(<member>=...)` returns F´'s
serialization of a bus struct built from its members' values, one pin per bus struct a role takes;
and `cdh_<role>(bus_bytes)` for a sensor, `cdh_<role>(icd_bytes)` for an actuator, returns F´'s
serialization of `convert_<role>`'s result for the struct its `<role>In` takes, which F´
deserializes from the bytes: the bus struct for a sensor, the GNC struct for an actuator.

`python -m fsw.codegen.bus_converter <directory>` writes the three files into the directory from
the contract, `fsw.codegen.deployment.contract_files()`; CMake runs it during `just fsw`, into the
build directory.
"""

import os
import sys
from collections.abc import Sequence
from pathlib import Path

import numpy as np

from fsw.codegen.deployment import REPOSITORY, contract_files
from fsw.codegen.fields import DTYPES, STRUCT_PRIMITIVES, form, plan
from fsw.codegen.fpp_model import Component, Model, read, struct_named
from fsw.codegen.roles import CONVERTER, Role, roles

__all__ = ["main", "render"]

_NUMBERS = [DTYPES[primitive] for primitive in STRUCT_PRIMITIVES]
"""`fsw.codegen.fields.STRUCT_PRIMITIVES`' primitives as `fsw.codegen.fields.form` gives them."""


def _cpp(name: str) -> str:
    """A qualified FPP name as C++ names it.

    Args:
        name: such as `Bus.ImuSensorMsg`.

    Returns:
        Such as `Bus::ImuSensorMsg`.
    """
    return name.replace(".", "::")


def _ends(role: Role) -> tuple[tuple[str, str], tuple[str, str]]:
    """The struct a role's conversion takes, and the one it gives, each with its variable's name.

    Args:
        role: the role.

    Returns:
        `(source, variable)` then `(target, variable)`: for a sensor, its bus struct `bus` to its
        GNC struct `icd`; for an actuator, the reverse.
    """
    bus, icd = (role.bus, "bus"), (role.icd, "icd")
    return (bus, icd) if role.sensor else (icd, bus)


def _copies(model: Model, role: Role) -> list[str]:
    """The statements filling the struct a role's conversion gives from the struct it takes.

    Args:
        model: the model.
        role: the role.

    Returns:
        A statement per field, copying its array element by element.

    Raises:
        ValueError: a field breaks `fsw.codegen.fields.plan`'s rule, or is not a one-dimensional
            array of one of `fsw.codegen.fields.STRUCT_PRIMITIVES`, naming it.
    """
    (source, source_var), (target, target_var) = _ends(role)
    source_struct, target_struct = struct_named(model.types, source), struct_named(model.types, target)
    sources = {m.name.lower(): (m.name, form(m, model.types)) for m in source_struct.members}
    statements = []
    for member, name, (shape, element) in plan(target_struct, model.types, sources, source):
        if len(shape) != 1 or not isinstance(element, np.dtype) or element not in _NUMBERS:
            raise ValueError(
                f"{target}.{member.name} is {shape} {element}, which the F´ CDH does not copy:"
                " it copies one-dimensional arrays of fsw.codegen.fields.STRUCT_PRIMITIVES' primitives"
            )
        statements.append(
            f"        for (FwSizeType i = 0; i < {shape[0]}; i++) {{\n"
            f"            {target_var}.get_{member.name}()[i] = {source_var}.get_{name}()[i];\n"
            "        }"
        )
    return statements


_HEADER = """\
// Generated by fsw.codegen.bus_converter from {component}; never committed.
#ifndef CDH_BUSCONVERTER_HPP
#define CDH_BUSCONVERTER_HPP

#include "{base}"

namespace Cdh {{
{usings}
class BusConverter final : public BusConverterComponentBase {{
  public:
    explicit BusConverter(const char* compName);
{conversions}
  private:
{declarations}
}};

}}  // namespace Cdh

#endif
"""

_SOURCE = """\
// Generated by fsw.codegen.bus_converter from {component}; never committed.
#include "BusConverter.hpp"

namespace Cdh {{

BusConverter::BusConverter(const char* compName) : BusConverterComponentBase(compName) {{}}
{definitions}
}}  // namespace Cdh
"""

_CONVERSION = """
    //! Role {role}'s {gives} from its {takes}.
    static {target} convert_{role}(const {source}& {source_var}) {{
        {target} {target_var};
{copies}
        return {target_var};
    }}
"""

_HANDLER = """
void BusConverter::{signature} {{
    this->{output}_out(0, convert_{role}(msg));
}}
"""

_PINS = """\
// Generated by fsw.codegen.bus_converter from {component}; never committed.
#ifndef CDH_BUSCONVERTERPINS_HPP
#define CDH_BUSCONVERTERPINS_HPP

#include <pybind11/pybind11.h>
#include <pybind11/stl.h>

#include <array>
#include <stdexcept>
#include <string>
#include <vector>

#include "BusConverter.hpp"

namespace {{

//! A struct's F´ serialization; raises naming the struct when F´ refuses it.
template <typename T>
pybind11::bytes busConverterSerialized(const T& value, const char* name) {{
    U8 data[T::SERIALIZED_SIZE];
    Fw::ExternalSerializeBuffer buffer(data, sizeof data);
    const Fw::SerializeStatus status = value.serializeTo(buffer);
    if (status != Fw::FW_SERIALIZE_OK) {{
        throw std::runtime_error(std::string(name) + ": F´ serialization failed with status " +
                                 std::to_string(status));
    }}
    return pybind11::bytes(reinterpret_cast<const char*>(data), buffer.getSize());
}}

void busConverterPins(pybind11::module_& m) {{
{pins}
}}

}}  // namespace

#endif
"""

_BUS_PIN = """\
    m.def(
        "bus_{name}",
        []({parameters}) {{
            {bus} value;
{fills}
            return busConverterSerialized(value, "{qualified}");
        }},
        {arguments},
        "F´'s serialization of a {qualified} built from its members' values.");
"""

_ROLE_PIN = """\
    m.def(
        "cdh_{role}",
        [](const pybind11::bytes& {argument}) {{
            const std::string text = {argument};
            std::vector<U8> data(text.begin(), text.end());
            Fw::ExternalSerializeBuffer buffer(data.data(), data.size());
            buffer.setBuffLen(data.size());
            {source} msg;
            const Fw::SerializeStatus status = msg.deserializeFrom(buffer);
            if (status != Fw::FW_SERIALIZE_OK) {{
                throw std::runtime_error("cdh_{role}: deserializing {qualified} failed with F´ "
                                         "status " + std::to_string(status));
            }}
            return busConverterSerialized(Cdh::BusConverter::convert_{role}(msg), "cdh_{role}");
        }},
        pybind11::arg("{argument}"),
        "Role {role}'s {source_var} bytes, deserialized by F´ and converted by Cdh.BusConverter's "
        "generated conversion: F´'s serialization of the {target} it gives.");
"""


def _bus_pin(model: Model, qualified: str) -> str:
    """The pin building a bus struct from its members' values and returning F´'s serialization.

    Args:
        model: the model.
        qualified: the bus struct's qualified name.

    Returns:
        The pin's `m.def` statement.

    Raises:
        ValueError: a member is not an inline array of one of `fsw.codegen.fields.STRUCT_PRIMITIVES`,
            naming it.
    """
    bus = struct_named(model.types, qualified)
    parameters, fills, arguments = [], [], []
    for member in bus.members:
        if member.type not in STRUCT_PRIMITIVES or member.size is None:
            size = "" if member.size is None else f"[{member.size}] "
            raise ValueError(
                f"{qualified}.{member.name} is {size}{member.type}, which the bus pin does not"
                " take: it takes inline arrays of fsw.codegen.fields.STRUCT_PRIMITIVES' primitives"
            )
        parameters.append(f"const std::array<{member.type}, {member.size}>& {member.name}")
        fills.append(
            f"            for (FwSizeType i = 0; i < {member.size}; i++) {{\n"
            f"                value.get_{member.name}()[i] = {member.name}[i];\n"
            "            }"
        )
        arguments.append(f'pybind11::arg("{member.name}")')
    return _BUS_PIN.format(
        name=qualified.rsplit(".", 1)[-1],
        parameters=", ".join(parameters),
        bus=_cpp(qualified),
        fills="\n".join(fills),
        qualified=qualified,
        arguments=", ".join(arguments),
    )


def _pins(model: Model, found: list[Role]) -> str:
    """The test pins' header: a bus pin per distinct bus struct, and a CDH pin per role.

    Args:
        model: the model.
        found: the roles.

    Returns:
        The header's text.
    """
    buses = dict.fromkeys(role.bus for role in found)
    pins = [_bus_pin(model, bus) for bus in buses]
    for role in found:
        (source, source_var), (target, _) = _ends(role)
        pins.append(
            _ROLE_PIN.format(
                role=role.role,
                argument=f"{source_var}_bytes",
                source=_cpp(source),
                qualified=source,
                source_var=source_var,
                target=target,
            )
        )
    return _PINS.format(component=CONVERTER, pins="\n".join(pins))


def _usings(component: Component, found: list[Role]) -> str:
    """The using declarations naming each actuator role's bus port buffer and serializer in `Cdh`.

    Args:
        component: the converter.
        found: the roles.

    Returns:
        A comment and two declarations per actuator role, `<Port>` its `<role>Out`'s port type.
    """
    ports = {port.name: port.type for port in component.outputs}
    lines = []
    for role in found:
        if not role.sensor:
            port_type = ports[role.output]
            assert port_type is not None, f"{role.output} is a typed port"
            lines.extend(f"using {_cpp(port_type)}{suffix};" for suffix in ("PortBuffer", "PortSerializer"))
    if not lines:
        return ""
    comment = "// FPP 3.4.0 names a connected port's serializer unqualified, in this namespace."
    return "\n".join([comment, *lines]) + "\n"


def render(model: Model) -> dict[str, str]:
    """The component's C++, from `Cdh.BusConverter`'s roles.

    A role or a field the rule refuses raises `ValueError`, naming it.

    Args:
        model: the model holding the converter and its structs.

    Returns:
        Each file's text, by its name: `BusConverter.hpp`, `BusConverter.cpp` and
        `BusConverterPins.hpp`.
    """
    component = model.components[CONVERTER]
    base = Path(os.path.relpath(component.file.parent, REPOSITORY)) / "BusConverterComponentAc.hpp"
    found = roles(model)
    conversions, declarations, definitions = [], [], []
    for role in found:
        (source, source_var), (target, target_var) = _ends(role)
        conversions.append(
            _CONVERSION.format(
                role=role.role,
                gives="GNC struct" if role.sensor else "bus struct",
                takes="bus struct" if role.sensor else "GNC struct",
                target=_cpp(target),
                source=_cpp(source),
                source_var=source_var,
                target_var=target_var,
                copies="\n".join(_copies(model, role)),
            )
        )
        signature = f"{role.input}_handler(FwIndexType, const {_cpp(source)}& msg)"
        declarations.append(f"    void {signature} override;")
        definitions.append(_HANDLER.format(signature=signature, output=role.output, role=role.role))
    return {
        "BusConverter.hpp": _HEADER.format(
            usings=_usings(component, found),
            component=CONVERTER,
            base=base.as_posix(),
            conversions="".join(conversions),
            declarations="\n".join(declarations),
        ),
        "BusConverter.cpp": _SOURCE.format(component=CONVERTER, definitions="".join(definitions)),
        "BusConverterPins.hpp": _pins(model, found),
    }


def main(argv: Sequence[str]) -> None:
    """Writes the component's C++ from the contract into a directory.

    Args:
        argv: the directory, alone.
    """
    [directory] = argv
    out = Path(directory)
    out.mkdir(parents=True, exist_ok=True)
    for name, text in render(read(contract_files())).items():
        (out / name).write_text(text)


if __name__ == "__main__":
    main(sys.argv[1:])
