"""The `FswExtension` protocol, `lab/fsw_extension.pyi`, generated from a built `_wise_fsw_<configuration>`.

Every configuration's extension has the same fixed functions, `boot`, `uplink`, `step`, `pump`,
`telemetry` and `responses`, besides the `bus_<Struct>` and `cdh_<role>` pins
`fsw.codegen.bus_converter` generates per contract, which Python reaches only by computed name. The
protocol is pybind11-stubgen's stub of the extension with the fixed functions as methods: their
signatures and docstrings are the compiled module's own.

`python -m fsw.codegen.fsw_extension lab._wise_fsw_<configuration>` writes the stub beside that
extension, as `fsw_extension.pyi`; CMake runs it during `just fsw`.
"""

import ast
import subprocess
import sys
import tempfile
from collections.abc import Sequence
from importlib import util
from pathlib import Path

__all__ = ["main", "render"]

_PINS = ("bus_", "cdh_")
"""The prefixes of the per-contract pins `fsw.codegen.bus_converter` generates; the protocol leaves them out."""

_HEADER = "# Generated by fsw.codegen.fsw_extension; never committed."


def _stub(module: str) -> ast.Module:
    """What pybind11-stubgen makes of a built extension.

    Args:
        module: the extension's module name, such as `lab._wise_fsw_ImuDeadReckoning`.

    Returns:
        The parsed stub.
    """
    with tempfile.TemporaryDirectory() as directory:
        subprocess.run(
            [sys.executable, "-m", "pybind11_stubgen", module, "--exit-code", "-o", directory],
            check=True,
        )
        return ast.parse(Path(directory, *module.split(".")).with_suffix(".pyi").read_text())


def render(module: str) -> str:
    """The stub of `FswExtension` for an extension.

    Args:
        module: the extension's module name, such as `lab._wise_fsw_ImuDeadReckoning`.

    Returns:
        The stub's text: stubgen's imports and a `Protocol` whose methods are the extension's
        functions that are not `bus_*` or `cdh_*` pins.
    """
    stub = _stub(module)
    imports = [node for node in stub.body if isinstance(node, ast.Import | ast.ImportFrom)]
    methods = [node for node in stub.body if isinstance(node, ast.FunctionDef) and not node.name.startswith(_PINS)]
    for method in methods:
        method.args.args.insert(0, ast.arg("self"))
    docstring = ast.Expr(
        ast.Constant(
            f"The fixed functions of every `_wise_fsw_<configuration>` extension, as pybind11-stubgen gives {module}'s."
        )
    )
    protocol = ast.ClassDef(
        name="FswExtension",
        bases=[ast.Name("Protocol")],
        keywords=[],
        body=[docstring, *methods],
        decorator_list=[],
        type_params=[],
    )
    body = [*imports, ast.ImportFrom("typing", [ast.alias("Protocol")], 0), protocol]
    return _HEADER + "\n" + ast.unparse(ast.fix_missing_locations(ast.Module(body, []))) + "\n"


def main(argv: Sequence[str]) -> None:
    """Writes the stub beside the extension it was read from.

    Args:
        argv: the extension's module name, alone.

    Raises:
        ModuleNotFoundError: the extension is not built.
    """
    [module] = argv
    spec = util.find_spec(module)
    if spec is None or spec.origin is None:
        raise ModuleNotFoundError(f"{module} is not built; run `just fsw`")
    Path(spec.origin).with_name("fsw_extension.pyi").write_text(render(module))


if __name__ == "__main__":
    main(sys.argv[1:])
